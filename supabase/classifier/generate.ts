// Turns dictionary.tsv into the migration that loads public.classifier_terms.
// Usage: deno run --allow-read --allow-write generate.ts <migration.sql>
// Create the migration first (`supabase migration new classifier_dictionary_<n>`);
// a migration already on main is never edited.

export const categories = [
  "produce",
  "bakery",
  "chilled",
  "meat",
  "pantry",
  "sweets",
  "drinks",
  "frozen",
  "household",
  "drugstore",
] as const;

export type Category = typeof categories[number];
export type Term = { term: string; category: Category };

const termPattern = /^[a-zäöüß]+( [a-zäöüß]+)*$/;

export function parseDictionary(tsv: string): Term[] {
  const seen = new Map<string, number>();
  const terms: Term[] = [];
  tsv.split("\n").forEach((raw, index) => {
    const line = raw.trimEnd();
    const at = `dictionary.tsv:${index + 1}`;
    if (line === "" || line.startsWith("#")) return;
    const fields = line.split("\t");
    if (fields.length !== 2) {
      throw new Error(`${at}: expected "term<TAB>category"`);
    }
    const [term, category] = fields;
    if (!termPattern.test(term)) {
      throw new Error(`${at}: invalid term "${term}"`);
    }
    if (!(categories as readonly string[]).includes(category)) {
      throw new Error(`${at}: unknown category "${category}"`);
    }
    const first = seen.get(term);
    if (first !== undefined) {
      throw new Error(`${at}: "${term}" repeats line ${first}`);
    }
    seen.set(term, index + 1);
    terms.push({ term, category: category as Category });
  });
  return terms;
}

export function toMigration(terms: Term[]): string {
  const rows = [...terms]
    .sort((a, b) => a.term < b.term ? -1 : a.term > b.term ? 1 : 0)
    .map(({ term, category }) => `  ('${term}', '${category}')`);
  return [
    "-- Generated by supabase/classifier/generate.ts from supabase/classifier/dictionary.tsv.",
    "-- Edit the TSV and generate a new migration; do not edit this file.",
    "",
    "truncate public.classifier_terms;",
    "",
    "insert into public.classifier_terms (term, category) values",
    rows.join(",\n") + ";",
    "",
  ].join("\n");
}

export const dictionaryUrl = new URL("./dictionary.tsv", import.meta.url);
export const migrationsUrl = new URL("../migrations/", import.meta.url);

if (import.meta.main) {
  const [target] = Deno.args;
  if (!target) {
    console.error("usage: generate.ts <migration.sql>");
    Deno.exit(2);
  }
  const terms = parseDictionary(await Deno.readTextFile(dictionaryUrl));
  await Deno.writeTextFile(target, toMigration(terms));
  console.log(`${terms.length} terms -> ${target}`);
}
